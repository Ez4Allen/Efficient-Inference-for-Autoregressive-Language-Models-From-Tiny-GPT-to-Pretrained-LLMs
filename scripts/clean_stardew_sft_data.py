"""Clean and audit the Stardew SFT candidate pool (PR1, Steps 3-7).

Reads the immutable raw candidate pool (``data/stardew/candidates.jsonl``)
and produces a normalized candidate pool with a controlled taxonomy, honest
review-state metadata, canonical source pages, deterministic knowledge
grouping, and an explicit rejected-record trail. This script never modifies
the raw input file.

If ``data/stardew/sft/review_log.jsonl`` exists, human review decisions in
it are applied on top of the automated pass and take precedence. Do not
hand-edit ``candidates.normalized.jsonl`` directly to record a review
decision -- it is regenerated by this script and any such edit is silently
lost on the next run. Add an entry to the review log instead.

This script does NOT decide train/validation/eval membership -- that is
``scripts/split_stardew_sft_data.py``'s job, which consumes this script's
normalized output.

Outputs:
    data/stardew/sft/candidates.normalized.jsonl  (all records, normalized)
    data/stardew/sft/rejected.jsonl               (rejected subset only)
    data/stardew/reports/sft_cleaning_report.json (taxonomy + dedup + leakage evidence)

Usage:
    python scripts/clean_stardew_sft_data.py \\
        --input data/stardew/candidates.jsonl \\
        --outdir data/stardew/sft \\
        --report data/stardew/reports/sft_cleaning_report.json
"""

from __future__ import annotations

